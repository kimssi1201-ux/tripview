const generated = JSON.parse(await fs.readFile(POSTS_PATH, "utf8"));
const legacy = JSON.parse(await fs.readFile(LEGACY_PATH, "utf8").catch(() => "[]"));
let updated = 0;
let added = 0;

for (const plan of indoorPlans) {
  const slug = `travel-${plan.id}`;
  const previousIndex = generated.findIndex((post) => post.slug === slug);
  const previous = previousIndex >= 0 ? generated[previousIndex] : {};
  const nextPost = buildPost(plan, findLegacy(legacy, plan.id), previous);
  if (previousIndex >= 0) {
    generated[previousIndex] = nextPost;
    updated += 1;
  } else {
    generated.unshift(nextPost);
    added += 1;
  }
}

generated.sort((a, b) => String(b.sortDate || "").localeCompare(String(a.sortDate || "")) || String(a.slug).localeCompare(String(b.slug)));
await fs.writeFile(POSTS_PATH, `${JSON.stringify(generated, null, 2)}\n`, "utf8");
console.log(`Indoor posts added ${added}, updated ${updated}.`);
