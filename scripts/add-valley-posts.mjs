const sourcePosts = JSON.parse(await readFile(SOURCE_PATH, "utf8"));
const sourceBySlug = new Map(sourcePosts.map((post) => [post.slug, post]));

function toPost(target) {
  const source = sourceBySlug.get(target.sourceSlug);
  if (!source?.image) throw new Error(`Missing source image: ${target.sourceSlug}`);
  const slug = `travel-${target.sourceSlug.replace(/^tour-/, "")}`;
  return {
    contentid: target.sourceSlug.replace(/^tour-/, ""),
    slug,
    title: target.title,
    sourceTitle: source.title,
    description: target.intro,
    category: "국내여행",
    region: target.region,
    date: TODAY_LABEL,
    sortDate: TODAY_SORT,
    read: "약 7분",
    image: source.image,
    images: [source.image],
    alt: `${source.title} 이미지`,
    excerpt: target.intro,
    keywords: target.keywords,
    info: [
      ["장소", source.title],
      ["주소", target.address],
      ["문의", "방문 전 확인 필요"],
      ["요금", "무료 또는 현장 안내 기준"],
      ["운영 확인", "날씨·통제·이용 가능 여부는 방문 전 확인"],
      ["방문 포인트", "물길 산책, 여름 풍경, 주변 여행 동선"]
    ],
    memo: [
      `지역: ${target.region}`,
      "유형: 계곡·물길 여행",
      "핵심 체크: 우천 뒤 수위, 미끄럼, 주차, 화장실, 귀가 동선",
      "방문 전 확인: 현장 통제와 날씨에 따라 물가 접근 범위가 달라질 수 있음"
    ],
    tourApi: {
      contentTypeId: "12",
      overview: "",
      homepage: "",
      mapx: "",
      mapy: "",
      intro: {}
    },
    sections: [...target.sections, ...(EXTRA_SECTIONS[target.sourceSlug] || [])],
    faq: target.faq,
    manualValleyPostVersion: 1
  };
}

